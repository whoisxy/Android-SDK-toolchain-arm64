#!/usr/bin/env python3
"""Generate a local task and an Actions entry point for every implemented recipe."""
import argparse
import json
from pathlib import Path
from common import ROOT, registry


def generated():
    dependencies = registry()
    files = {}
    for name in sorted(dependencies):
        files[f"tasks/{name}.sh"] = '''#!/usr/bin/env bash
set -euo pipefail
root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
exec "$root/task" NAME "$@"
'''.replace("NAME", name)
        files[f".github/workflows/build-{name}.yml"] = '''# Generated by scripts/generate-tasks.py
name: Build and release NAME
on:
  workflow_dispatch:
    inputs:
      ref:
        description: Optional full Git commit hash or tag; empty uses the recipe pin
        type: string
        default: ''
      libc:
        description: ARM64 target libc
        type: choice
        options: [bionic, glibc, musl]
        default: bionic
      runner:
        description: Optional JSON runner labels; empty uses the recipe default
        type: string
        default: ''
      release_repository:
        description: Optional OWNER/REPOSITORY override; empty uses the registry or this repository
        type: string
        default: ''
permissions:
  contents: write
jobs:
  dependency:
    uses: ./.github/workflows/_build-release.yml
    with:
      dependency: NAME
      ref: ${{ inputs.ref }}
      libc: ${{ inputs.libc }}
      runner: ${{ inputs.runner }}
      release_repository: ${{ inputs.release_repository }}
    secrets: inherit
'''.replace("NAME", name)
    choices = "\n".join("          - " + name for name in sorted(dependencies))
    files[".github/workflows/build.yml"] = '''# Generated by scripts/generate-tasks.py
name: Build and release dependency
on:
  workflow_dispatch:
    inputs:
      dependency:
        description: Dependency task
        type: choice
        required: true
        options:
CHOICES
      ref:
        description: Optional full Git commit hash or tag; empty uses the recipe pin
        type: string
        default: ''
      libc:
        description: ARM64 target libc
        type: choice
        options: [bionic, glibc, musl]
        default: bionic
      runner:
        description: Optional JSON runner labels; empty uses the recipe default
        type: string
        default: ''
      release_repository:
        description: Optional OWNER/REPOSITORY override
        type: string
        default: ''
permissions:
  contents: write
jobs:
  dependency:
    uses: ./.github/workflows/_build-release.yml
    with:
      dependency: ${{ inputs.dependency }}
      ref: ${{ inputs.ref }}
      libc: ${{ inputs.libc }}
      runner: ${{ inputs.runner }}
      release_repository: ${{ inputs.release_repository }}
    secrets: inherit
'''.replace("CHOICES", choices)
    rows = ["# Dependency tasks", "", "Every row has a `tasks/NAME.sh [HASH_OR_TAG] --libc bionic|glibc|musl` entry point and an individual Actions workflow. Output is always ARM64; libc defaults to bionic.", "",
            "| Task | Output kind | Backend | Default source commit | Supported libc | Runner |", "|---|---|---|---|---|---|"]
    for name, spec in sorted(dependencies.items()):
        rows.append(f"| `{name}` | {spec['kind']} | {spec['backend']} | `{spec['default_ref']}` | {', '.join(spec.get('supported_libcs', ['bionic','glibc','musl']))} | {', '.join(spec.get('runner', ['ubuntu-24.04']))} |")
    rows += ["", "These are implemented recipes, not a claim that every recipe has completed a CI build. Consult Actions and Releases for observed results.",
             "Refs must belong to the recipe's source repository. Different upstream versions may need recipe changes. Source distributions such as depot-tools and repo package interpreted tooling; they do not claim to compile upstream runtime binaries.", ""]
    files["docs/tasks.md"] = "\n".join(rows)
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generated().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit("Generated task is stale: " + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            if path.suffix == ".sh":
                path.chmod(0o755)
    print("Task entry points are current" if args.check else "Generated dependency task entry points")
