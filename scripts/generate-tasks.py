#!/usr/bin/env python3
"""Generate the build workflow dropdown and the dependency list."""
import argparse
from common import ROOT, registry


def generated():
    dependencies = {name: spec for name, spec in registry().items() if spec.get("release_task", True)}
    files = {}
    ordered = sorted(dependencies, key=lambda name: (dependencies[name].get("source_required", False), name))
    choices = "\n".join("          - " + name for name in ordered)
    files[".github/workflows/build.yml"] = '''# Generated by scripts/generate-tasks.py
name: Build and release dependency
on:
  workflow_dispatch:
    inputs:
      dependency:
        description: Dependency task
        type: choice
        required: true
        options:
CHOICES
      ref:
        description: Full Git commit hash or tag (required for generic-cmake, otherwise defaults to the recipe pin)
        type: string
        default: ''
      source_url:
        description: Public GitHub repository URL for generic-cmake
        type: string
        default: ''
      libc:
        description: ARM64 target libc
        type: choice
        options: [bionic, glibc, musl]
        default: bionic
      runner:
        description: Optional JSON runner labels; empty uses the recipe default
        type: string
        default: ''
      release_repository:
        description: Optional OWNER/REPOSITORY override
        type: string
        default: ''
permissions:
  contents: write
jobs:
  dependency:
    uses: ./.github/workflows/_build-release.yml
    with:
      dependency: ${{ inputs.dependency }}
      ref: ${{ inputs.ref }}
      source_url: ${{ inputs.source_url }}
      libc: ${{ inputs.libc }}
      runner: ${{ inputs.runner }}
      release_repository: ${{ inputs.release_repository }}
    secrets: inherit
'''.replace("CHOICES", choices)
    rows = ["# Dependency tasks", "", "Pick a dependency in **Build and release dependency** or use `./task NAME [HASH_OR_TAG] --libc bionic|glibc|musl`. Output targets ARM64 and libc defaults to bionic.", "",
            "| Task | Output kind | Backend | Default source commit | Supported libc | Runner |", "|---|---|---|---|---|---|"]
    for name in ordered:
        spec = dependencies[name]
        source = "Source URL and ref required" if spec.get("source_required") else f"`{spec['default_ref']}`"
        rows.append(f"| `{name}` | {spec['kind']} | {spec['backend']} | {source} | {', '.join(spec.get('supported_libcs', ['bionic','glibc','musl']))} | {', '.join(spec.get('runner', ['ubuntu-24.04']))} |")
    rows += ["", "These are implemented recipes, not a claim that every recipe has completed a CI build. Consult Actions and Releases for observed results.",
             "Refs must belong to the recipe's source repository. Different upstream versions may need recipe changes.", ""]
    files["docs/tasks.md"] = "\n".join(rows)
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generated().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit("Generated task is stale: " + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("Task entry points are current" if args.check else "Generated dependency task entry points")
